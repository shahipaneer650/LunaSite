-- 1. Lunar Missions Table
CREATE TABLE IF NOT EXISTS public.lunar_missions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    agency TEXT NOT NULL,
    landing_date DATE,
    latitude_deg DOUBLE PRECISION NOT NULL,
    longitude_deg DOUBLE PRECISION NOT NULL,
    site_name TEXT,
    status TEXT NOT NULL,
    category TEXT,
    description TEXT,
    scientific_significance TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Lunar Features & Permanently Shadowed Regions (PSRs)
CREATE TABLE IF NOT EXISTS public.lunar_features (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    feature_type TEXT NOT NULL,
    latitude_deg DOUBLE PRECISION NOT NULL,
    longitude_deg DOUBLE PRECISION NOT NULL,
    diameter_km DOUBLE PRECISION,
    depth_m DOUBLE PRECISION,
    permanently_shadowed BOOLEAN DEFAULT FALSE,
    ice_potential TEXT,
    description TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Saved Landing Sites (User Bookmarks)
CREATE TABLE IF NOT EXISTS public.saved_sites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    latitude_deg DOUBLE PRECISION NOT NULL,
    longitude_deg DOUBLE PRECISION NOT NULL,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Site Assessments History
CREATE TABLE IF NOT EXISTS public.site_assessments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_name TEXT,
    latitude_deg DOUBLE PRECISION NOT NULL,
    longitude_deg DOUBLE PRECISION NOT NULL,
    overall_score DOUBLE PRECISION NOT NULL,
    suitability_rating TEXT NOT NULL,
    illumination_score DOUBLE PRECISION,
    comm_score DOUBLE PRECISION,
    slope_score DOUBLE PRECISION,
    recommendations JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. Custom Mission Profiles (User-Defined Grading Profiles)
CREATE TABLE IF NOT EXISTS public.custom_mission_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT DEFAULT '',
    weights_json JSONB NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable Row Level Security (RLS)
ALTER TABLE public.lunar_missions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.lunar_features ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.saved_sites ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.site_assessments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.custom_mission_profiles ENABLE ROW LEVEL SECURITY;

-- Allow public read/write access
CREATE POLICY "Public read lunar missions" ON public.lunar_missions FOR SELECT USING (true);
CREATE POLICY "Public read lunar features" ON public.lunar_features FOR SELECT USING (true);
CREATE POLICY "Public read/write saved sites" ON public.saved_sites FOR ALL USING (true);
CREATE POLICY "Public read/write assessments" ON public.site_assessments FOR ALL USING (true);
CREATE POLICY "Public read/write custom profiles" ON public.custom_mission_profiles FOR ALL USING (true);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_missions_coords ON public.lunar_missions (latitude_deg, longitude_deg);
CREATE INDEX IF NOT EXISTS idx_features_psr ON public.lunar_features (permanently_shadowed);
CREATE INDEX IF NOT EXISTS idx_saved_sites_created ON public.saved_sites (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_custom_profiles_created ON public.custom_mission_profiles (created_at DESC);

